export function levelForLap(lap: number): CivilizationLevel {
  return LEVELS[Math.min(lap, LEVELS.length) - 1];
}

export function lapLabel(lap: number): string {
  return lap <= LEVELS.length ? `レベル${lap}` : `レベル${LEVELS.length}・${lap}周目`;
}
